'use client';

/**
 * The inspector's Macro section, shown for a node tagged `use`: which macro use
 * generated it, that use's arguments as editable JSON (checked against the
 * macro's schema as the author types), and the two edits that keep the use and
 * its nodes in agreement — Re-expand (regenerate the nodes from the arguments)
 * and Detach (forget the use; its nodes become ordinary ones). Logic lives in
 * `macroEdits`; this file only renders it.
 */

import type { WorkflowSpec } from '@auto-swe/shared/workflow';
import { useEffect, useMemo, useState } from 'react';
import { Alert } from '@/components/ui/Alert';
import { Button } from '@/components/ui/Button';
import { Textarea } from '@/components/ui/Textarea';
import { InspectorSection } from './inspectorFields';
import { macroUseDisplayName } from './macroDisplay';
import {
  detachUseInSpec,
  formatUseArgs,
  macroUseInfo,
  parseUseArgsDraft,
  reexpandUseWithArgs,
} from './macroEdits';

export function MacroSection({
  spec,
  useId,
  onChangeSpec,
}: {
  spec: WorkflowSpec;
  useId: string;
  onChangeSpec: (next: WorkflowSpec) => void;
}) {
  const info = useMemo(() => macroUseInfo(spec, useId), [spec, useId]);
  const stored = formatUseArgs(info.args);
  const [draft, setDraft] = useState(stored);
  const [actionError, setActionError] = useState<string | null>(null);
  // A different use, or arguments changed underneath (a re-expand, a version switch).
  useEffect(() => {
    setDraft(stored);
    setActionError(null);
  }, [stored]);

  const parsed = info.macroRef && info.knownMacro ? parseUseArgsDraft(info.macroRef, draft) : null;
  const edited = draft !== stored;

  const reexpand = () => {
    if (!parsed?.ok) {
      return;
    }
    const result = reexpandUseWithArgs(spec, useId, edited ? parsed.args : undefined);
    if (result.ok) {
      setActionError(null);
      onChangeSpec(result.spec);
    } else {
      setActionError(result.error);
    }
  };
  const detach = () => {
    const result = detachUseInSpec(spec, useId);
    if (result.ok) {
      setActionError(null);
      onChangeSpec(result.spec);
    } else {
      setActionError(result.error);
    }
  };

  return (
    <InspectorSection title="Macro">
      <dl className="grid grid-cols-[auto_1fr] gap-x-3 gap-y-1 text-xs">
        <dt className="text-paper-500">Use</dt>
        <dd className="font-mono text-paper-200">{useId}</dd>
        <dt className="text-paper-500">Macro</dt>
        <dd className="font-mono text-paper-200">{info.macroRef ?? 'not declared'}</dd>
        <dt className="text-paper-500">Nodes</dt>
        <dd className="text-paper-200">{info.memberIds.length}</dd>
      </dl>
      <p className="text-xs text-paper-400">
        Generated by {macroUseDisplayName(spec, useId)}. Its nodes cannot be deleted or renamed one
        by one; change the arguments and re-expand, or detach the use to edit the nodes freely.
      </p>

      {info.drifted && (
        <Alert announce={false} title="Edited by hand" variant="warning">
          These nodes no longer match what the macro generates from its arguments, and a save is
          refused while they disagree. Re-expand to regenerate them (the hand edits are lost), or
          detach the use to keep the edits as ordinary nodes.
        </Alert>
      )}
      {info.problems.length > 0 && (
        <ul aria-label="Macro problems" className="space-y-1 text-xs text-danger-400">
          {info.problems.map((p) => (
            <li key={`${p.code}:${p.nodeId ?? ''}:${p.message}`}>{p.message}</li>
          ))}
        </ul>
      )}

      {info.macroRef && info.knownMacro && (
        <Textarea
          className="h-40 text-xs"
          compact
          error={parsed && !parsed.ok ? parsed.error : undefined}
          hint="JSON, checked against the macro's argument schema"
          id={`macro-args-${useId}`}
          label="Arguments"
          onChange={(e) => setDraft(e.target.value)}
          spellCheck={false}
          value={draft}
        />
      )}
      {actionError && <Alert title="Could not apply">{actionError}</Alert>}
      <div className="flex flex-wrap gap-2">
        {info.macroRef && info.knownMacro && (
          <Button
            disabled={!parsed?.ok}
            onClick={reexpand}
            size="sm"
            title="Replace this use's nodes with a fresh expansion of the arguments"
            variant="secondary"
          >
            Re-expand
          </Button>
        )}
        <Button
          onClick={detach}
          size="sm"
          title="Forget the macro use; its nodes stay as ordinary nodes"
          variant="ghost"
        >
          Detach
        </Button>
      </div>
    </InspectorSection>
  );
}
