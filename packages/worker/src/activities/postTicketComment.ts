import { prisma } from '@auto-swe/shared/db';
import { createIssueTrackerProvider } from '@auto-swe/shared/lib/integrations/registry';
import { resolveIssueTrackerConfig } from '@auto-swe/shared/lib/systemConfig';
import { logWarn } from '../lib/activityLog.js';
import { redactCiLog } from '../lib/ciLogGuard.js';
import { getErrorMessage } from '../lib/errors.js';

/** Under Jira's 32,767-character comment limit, with room for the marker. */
export const MAX_TICKET_COMMENT_CHARS = 30_000;
export const TICKET_COMMENT_TRUNCATION_MARKER = '\n\n[comment truncated by auto-swe]';

export interface PostTicketCommentInput {
  workRequestId: string;
  body: string;
  /** First line of the comment, followed by a blank line. */
  heading?: string;
}

export type PostTicketCommentResult = { posted: true } | { posted: false; reason: string };

/**
 * GitHub and Linear render the comment as markdown, so text the run produced could ping people
 * or load a remote image. A zero-width joiner after the `@` stops the mention without visibly
 * changing the text, and an image becomes a plain link. Jira gets one ADF text node, which
 * renders neither, so its text is left alone.
 */
function neutraliseMarkdown(text: string): string {
  // `_` may open emphasis (`_@alice_` still pings), and a run of `!` would re-form `![` after one
  // pass, so both are matched whole.
  return text.replace(/(^|[^A-Za-z0-9])@(?=[A-Za-z0-9])/g, '$1@‍').replace(/!+\[/g, '[');
}

function commentText(body: string, heading: string | undefined, provider: string): string {
  const head = heading?.trim();
  const redacted = redactCiLog(head ? `${head}\n\n${body}` : body);
  const text = provider === 'jira' ? redacted : neutraliseMarkdown(redacted);
  if (text.length <= MAX_TICKET_COMMENT_CHARS) {
    return text;
  }
  let cut = MAX_TICKET_COMMENT_CHARS - TICKET_COMMENT_TRUNCATION_MARKER.length;
  const last = text.charCodeAt(cut - 1);
  if (last >= 0xd800 && last <= 0xdbff) {
    cut -= 1;
  }
  return `${text.slice(0, cut)}${TICKET_COMMENT_TRUNCATION_MARKER}`;
}

/**
 * Post one comment to the run's tracker ticket through the global issue-tracker config.
 *
 * Best-effort, like the tracker sync: every outcome other than a posted comment is returned as
 * `{ posted: false, reason }`, never thrown, so a tracker outage cannot fail the run. Never
 * throwing also means the activity is never retried into a second comment.
 */
export async function postTicketComment(
  input: PostTicketCommentInput
): Promise<PostTicketCommentResult> {
  if (input.body.trim() === '') {
    return { posted: false, reason: 'the comment body is empty' };
  }
  try {
    const run = await prisma.runInput.findUnique({
      select: { externalTicketId: true, ticketIsSynthetic: true },
      where: { id: input.workRequestId },
    });
    if (!run?.externalTicketId) {
      return { posted: false, reason: 'the run has no ticket' };
    }
    if (run.ticketIsSynthetic) {
      return {
        posted: false,
        reason: `the run's ticket id ${run.externalTicketId} was generated by the platform, not read from a tracker`,
      };
    }
    const config = await resolveIssueTrackerConfig();
    if (!config.provider) {
      return { posted: false, reason: 'no issue tracker is configured' };
    }
    // No provider logger: its warnings carry the raw provider error, which can quote a request.
    const provider = createIssueTrackerProvider(config, {});
    if (!provider) {
      return {
        posted: false,
        reason: `the ${config.provider} tracker settings are incomplete or were refused`,
      };
    }
    if (
      await provider.addComment(
        run.externalTicketId,
        commentText(input.body, input.heading, config.provider)
      )
    ) {
      return { posted: true };
    }
    const reason = `the ${config.provider} tracker did not accept the comment on ${run.externalTicketId}`;
    logWarn(`postTicketComment: ${reason}`, { workRequestId: input.workRequestId });
    return { posted: false, reason };
  } catch (err) {
    logWarn('postTicketComment failed', {
      error: getErrorMessage(err),
      workRequestId: input.workRequestId,
    });
    return { posted: false, reason: 'the comment could not be posted (see the worker log)' };
  }
}
