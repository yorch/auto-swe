/**
 * Pinning an approved run plan as a run's spec.
 *
 * The hidden "Planned Run" system template carries a failing placeholder spec. When
 * `createWorkflowRun` creates a run of it, this module loads the plan named by the launch payload,
 * refuses unless every condition the approval established still holds, and hands back the plan's
 * own spec for the run to snapshot. All reads happen here, in the activity: the workflow only ever
 * sees the spec `createWorkflowRun` returns, exactly as it does for every other template, so the
 * pin is replay-deterministic by the same argument.
 *
 * Every refusal is a non-retryable `ApplicationFailure` with a stable `type` (`PLAN_*`) and no
 * plan content in the message: a retry cannot make an unapproved, expired or tampered plan
 * approved, and a refused plan is regenerated by its owner, never repaired here.
 */

export const PLANNED_RUN_REFUSAL_TYPE = 'PLANNED_RUN_REFUSED';

function refuse(code: string, message: string): ApplicationFailure {
  return ApplicationFailure.nonRetryable(`${code}: ${message}`, PLANNED_RUN_REFUSAL_TYPE, { code });
}

export interface PlannedRunPinInput {
  /** `CreateWorkflowRunInput.payload`: the launch payload, untrusted. */
  payload?: unknown;
  /** The person this run acts as (`RunRequest.launchedById`). */
  launchedById?: string | null | undefined;
  /** The repository the run acts on (`CreateWorkflowRunInput.runConnectionId`). */
  runConnectionId?: string | null | undefined;
  /** This execution's workflow id, to recognise a Temporal retry of a pin already made. */
  workflowId: string;
}

/** The run's team and organisation: what its agents resolve under. */
export interface PlannedRunScope {
  teamId?: string | null | undefined;
  orgId?: string | null | undefined;
  /** The Planned Run template's id: the WORKFLOW_TEMPLATE tier of the agent cascade. */
  workflowTemplateId?: string | null | undefined;
}

export interface PinnedPlan {
  planId: string;
  /** The plan's team, for the tenant-scoped claim. */
  teamId: string;
  spec: WorkflowSpec;
  mode: RunPlanMode;
  /**
   * The id of the run row that already claimed the plan, when this call is a retry of the attempt
   * that did. The claim is then not made again.
   */
  claimedByRunId: string | null;
}

type Db = Pick<
  typeof prisma,
  'runPlan' | 'workflowRun' | 'agent' | 'user' | 'connection' | 'organizationMembership'
>;

const ACCESS_LOG: AccessLog = {
  warn: (obj, msg) => {
    try {
      log.warn(msg ?? 'repo access', obj as Record<string, unknown>);
    } catch {
      // Outside an activity context there is no logger; the verdict is what matters.
    }
  },
};

/** The decision the launcher gets for the repository now. Overridable so a suite need not mock GitHub. */
export type LauncherAccessCheck = (
  db: Db,
  launcherId: string,
  connectionId: string
) => Promise<void>;

/**
 * Re-take the launch decision for the person the run acts as: the approval is days or minutes old,
 * and a person who was deactivated, removed from the repository's teams or
 * org, or lost GitHub access since is refused here. Same shared decision the gateway and a
 * scheduled fire take (`decideRepoAccess`), so the three cannot disagree about what "may launch"
 * means.
 */
export const assertLauncherStillAuthorized: LauncherAccessCheck = async (
  db,
  launcherId,
  connectionId
) => {
  const user = await db.user.findUnique({
    select: { id: true, isActive: true, role: true },
    where: { id: launcherId },
  });
  if (!user?.isActive) {
    throw refuse('PLAN_LAUNCHER_INACTIVE', 'the person who approved the plan is no longer active');
  }
  const repo = await db.connection.findUnique({
    select: {
      githubApiUrl: true,
      githubUrl: true,
      id: true,
      installation: { select: { host: true, installationId: true, isActive: true } },
      isActive: true,
      organizationName: true,
      repoName: true,
      scmProvider: true,
      shares: {
        select: {
          ...repoMembersSelect({ userId: true }, { userId: user.id }).shares.select,
          teamId: true,
        },
      },
      team: {
        select: {
          isActive: true,
          memberships: { select: { userId: true }, where: { userId: user.id } },
          organization: { select: { isActive: true } },
          orgId: true,
        },
      },
      teamId: true,
      type: true,
    },
    where: { id: connectionId },
  });
  if (!repo?.isActive || !repo.team.isActive || !repo.team.organization.isActive) {
    throw refuse('PLAN_REPOSITORY_INACTIVE', 'the repository, team or organization is not active');
  }
  // Fail closed on an unreadable gate: nobody is here to retry.
  const gate = await resolveRepoAccessGateOrLastKnown();
  if (!gate) {
    throw refuse('PLAN_ACCESS_UNREADABLE', 'the repository access policy could not be read');
  }
  const verdict = await decideRepoAccess(
    db as never,
    { role: user.role as PlatformRole, sub: user.id },
    repo,
    gate,
    ACCESS_LOG,
    'start-new-work',
    'caller'
  );
  if (!verdict.allowed) {
    throw refuse(
      'PLAN_LAUNCHER_ACCESS_LOST',
      REPO_ACCESS_REFUSAL_MESSAGE[verdict.reason] ?? 'the launcher cannot use the repository'
    );
  }
  if (!isPlatformAdmin(user)) {
    const membership = await db.organizationMembership.findUnique({
      select: { userId: true },
      where: { userId_orgId: { orgId: repo.team.orgId, userId: user.id } },
    });
    if (!membership) {
      throw refuse('PLAN_LAUNCHER_ACCESS_LOST', 'the launcher left the repository organization');
    }
  }
};

/** Load and verify the plan a Planned Run launch names. Throws a non-retryable refusal. */
export async function loadApprovedPlan(
  input: PlannedRunPinInput,
  scope: PlannedRunScope,
  now: Date = new Date(),
  db: Db = prisma,
  checkLauncher: LauncherAccessCheck = assertLauncherStillAuthorized
): Promise<PinnedPlan> {
  const payload = PlannedRunPayloadSchema.safeParse(input.payload);
  if (!payload.success) {
    throw refuse(
      'PLAN_PAYLOAD_INVALID',
      `a ${PLANNED_RUN_TEMPLATE_NAME} launch carries exactly one field, planId`
    );
  }
  // A planned run acts as the person who approved it and never as the platform alone.
  if (!input.launchedById) {
    throw refuse('PLAN_NO_LAUNCHER', 'a planned run needs the person who approved it');
  }
  const plan = await db.runPlan.findUnique({ where: { id: payload.data.planId } });
  if (!plan) {
    throw refuse('PLAN_NOT_FOUND', 'the plan does not exist');
  }
  // A scrubbed plan kept its row (a run names it) but not its goal or its spec. Refused ahead of
  // every other check, a retry of a long-finished launch included: there is nothing to pin.
  if (plan.scrubbedAt !== null && plan.scrubbedAt !== undefined) {
    throw refuse(
      'PLAN_SCRUBBED',
      'the goal and plan body were removed from the plan record after the retention period'
    );
  }

  // A Temporal retry of an attempt whose claim committed finds the plan LAUNCHED by the run row
  // that attempt wrote. That is the one way past APPROVED.
  const existing = await db.workflowRun.findUnique({
    select: { id: true },
    where: { workflowId: input.workflowId },
  });
  const isRetry =
    plan.status === 'LAUNCHED' &&
    existing !== null &&
    plan.launchedWorkflowRunId !== null &&
    plan.launchedWorkflowRunId === existing.id;
  if (!isRetry && plan.status !== 'APPROVED') {
    throw refuse('PLAN_NOT_APPROVED', `the plan is ${plan.status}, not APPROVED`);
  }
  // A row under this workflow id that is not the plan's own claim is some other run's. Its stored
  // spec would be returned in place of the plan's (the upsert keeps the first), so refuse.
  if (!isRetry && existing !== null) {
    throw refuse('PLAN_WORKFLOW_ID_REUSED', 'another run already holds this workflow id');
  }
  // The plan is the owner's and was approved by the owner; the run acts as that same person.
  if (plan.approvedById === null || plan.approvedById !== input.launchedById) {
    throw refuse('PLAN_APPROVER_MISMATCH', 'the plan was not approved by the person launching it');
  }
  if (plan.ownerUserId !== input.launchedById) {
    throw refuse('PLAN_OWNER_MISMATCH', 'the plan belongs to another person');
  }
  if (!input.runConnectionId || plan.connectionId !== input.runConnectionId) {
    throw refuse('PLAN_REPOSITORY_MISMATCH', 'the plan was approved for another repository');
  }
  if (!isRetry && plan.expiresAt.getTime() <= now.getTime()) {
    throw refuse('PLAN_EXPIRED', 'the plan has expired');
  }
  let hash: string;
  try {
    hash = hashRunPlanSpec(plan.spec);
  } catch {
    throw refuse('PLAN_SPEC_TOO_DEEP', 'the stored spec is nested too deeply');
  }
  if (hash !== plan.specHash) {
    throw refuse('PLAN_SPEC_TAMPERED', 'the stored spec does not match the approved hash');
  }
  const mode = (RUN_PLAN_MODES as readonly string[]).includes(plan.mode)
    ? (plan.mode as RunPlanMode)
    : null;
  if (!mode) {
    throw refuse('PLAN_MODE_INVALID', 'the plan has an unknown mode');
  }

  let spec: WorkflowSpec;
  try {
    spec = parseWorkflowSpec(migrateSpec(plan.spec, SPEC_SCHEMA_VERSION));
  } catch {
    throw refuse('PLAN_SPEC_INVALID', 'the stored spec does not parse');
  }

  const mismatch = runPlanConsistencyIssue(plan, spec);
  if (mismatch) {
    throw refuse('PLAN_AGENT_MISMATCH', mismatch.replace(/'[^']*'/g, "'…'"));
  }

  if (isRetry) {
    return {
      claimedByRunId: existing?.id ?? null,
      mode,
      planId: plan.id,
      spec,
      teamId: plan.teamId,
    };
  }

  // The person the run acts as must still be allowed to start it: access can be taken away between
  // approval and launch. (A retry of an attempt that already claimed returned above: the run it
  // would pin has started.)
  await checkLauncher(db, input.launchedById, plan.connectionId);

  // The kill switch, taken again at launch: an approval can wait up to the launch window, and an
  // ADMIN who disabled run plans meanwhile means no approved plan starts. Resolved at the plan's
  // team and organization, as the gateway does. A failed read is not caught: like the gateway's
  // (which answers 500) it neither opens nor refuses, so Temporal retries the activity.
  const switches = await resolveSettings(['runPlans.enabled'], {
    ...(scope.orgId ? { orgId: scope.orgId } : {}),
    teamId: plan.teamId,
  });
  if (!switches['runPlans.enabled']) {
    throw refuse('PLAN_FEATURE_DISABLED', 'run plans are disabled');
  }

  // Re-checked at pin time, not trusted from approval: the rules may have tightened since, and the
  // stored reports are the generator's word, not this process's.
  const policy = checkSkeletonPolicy(spec, mode);
  if (!policy.ok) {
    throw refuse(
      'PLAN_POLICY_FAILED',
      `the skeleton policy refuses the plan (${policy.errors.map((e) => e.code).join(', ')})`
    );
  }
  const validation = validateSpec(spec, { rejectNonLaunchableAgents: true });
  if (validation.errors.length > 0) {
    throw refuse(
      'PLAN_SPEC_INVALID',
      `the spec fails validation (${validation.errors.map((e) => e.code).join(', ')})`
    );
  }

  const named = specAgentKeys(spec);
  const recorded =
    plan.agentPins && typeof plan.agentPins === 'object' && !Array.isArray(plan.agentPins)
      ? Object.keys(plan.agentPins as Record<string, unknown>)
      : [];
  const current = await resolveRunPlanAgentPins(db, [...recorded, ...named], scope);
  const drift = agentPinDrift(plan.agentPins, current, named);
  if (drift.length > 0) {
    throw refuse('PLAN_AGENT_DRIFT', `these agents changed since approval: ${drift.join(', ')}`);
  }

  return { claimedByRunId: null, mode, planId: plan.id, spec, teamId: plan.teamId };
}

/** The slice of a transaction client the claim writes through. */
interface ClaimTx {
  workflowRun: { upsert(args: never): Promise<{ id: string }> };
  runPlan: {
    updateMany(args: {
      data: { status: 'LAUNCHED'; launchedWorkflowRunId: string };
      where: { id: string; status: 'APPROVED'; teamId: string };
    }): Promise<{ count: number }>;
  };
}

/**
 * Write the run row and mark its plan LAUNCHED in one transaction. The mark is an
 * `updateMany where status = APPROVED`, so of two executions racing on one approval exactly one
 * matches; the other's transaction throws and takes its run row with it. A retry of the attempt
 * that already claimed (`claimedByRunId`) writes the (kept) row and claims nothing.
 */
export async function claimPlanWithRun<R extends { id: string }>(
  plan: PinnedPlan,
  runUpsert: unknown,
  db: {
    $transaction: <T>(fn: (tx: never) => Promise<T>) => Promise<T>;
  } = prisma as never
): Promise<R> {
  return db.$transaction(async (txNever) => {
    const tx = txNever as unknown as ClaimTx;
    const run = (await tx.workflowRun.upsert(runUpsert as never)) as R;
    if (plan.claimedByRunId === null) {
      const claim = await tx.runPlan.updateMany({
        data: { launchedWorkflowRunId: run.id, status: 'LAUNCHED' },
        where: { id: plan.planId, status: 'APPROVED', teamId: plan.teamId },
      });
      if (claim.count !== 1) {
        throw refuse('PLAN_ALREADY_LAUNCHED', 'the plan was launched by another run');
      }
    }
    return run;
  });
}
